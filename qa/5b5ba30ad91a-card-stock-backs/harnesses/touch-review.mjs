import fs from 'node:fs/promises';
import {chromium,expect} from '/workspace/digipology/node_modules/@playwright/test/index.mjs';
const sourceRef=process.argv[2]??null;
const origin='http://127.0.0.1:8787';
const folder=`/workspace/release-receipts/2026-10-29-themed-card-backs/${process.argv[3]??'touch-corrected'}`;
await fs.mkdir(folder,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-angle=swiftshader']});
const errors=[];const observations={sourceRef,viewport:{width:390,height:844},input:'Chromium touch emulation; not physical phone hardware',errors};
try{
  const context=await browser.newContext({baseURL:origin,viewport:observations.viewport,hasTouch:true,isMobile:true,deviceScaleFactor:1});
  const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
  const actions=[];let watchActions=false;
  page.on('websocket',socket=>socket.on('framesent',frame=>{if(!watchActions)return;const message=JSON.parse(String(frame.payload));if(message.type==='action_request')actions.push(message.action?.type);}));
  await page.goto('/');await page.getByRole('button',{name:/host a room/i}).first().tap();
  await page.getByLabel('Game',{exact:true}).selectOption('first-deal');await page.getByLabel('Display name',{exact:true}).fill('Touch audit');
  await page.getByRole('button',{name:'Create table',exact:true}).tap();await page.getByRole('button',{name:'Enter table',exact:true}).tap();
  await expect(page.getByRole('img',{name:'Live synchronized 3D tabletop',exact:true})).toHaveAttribute('data-render-state','ready',{timeout:30000});
  await expect(page.getByRole('button',{name:'Show 1 player',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Shuffle deck',exact:true}).tap();await page.getByRole('button',{name:'Draw card',exact:true}).tap();
  await expect(page.getByRole('button',{name:'Inspect 7 of Diamonds',exact:true})).toBeVisible();await page.getByRole('button',{name:'Draw card',exact:true}).tap();
  await expect(page.getByRole('button',{name:'Inspect Queen of Clubs',exact:true})).toBeVisible();
  const players=page.getByRole('complementary',{name:'Players',exact:true});
  if(!(await players.isVisible()))await page.getByRole('button',{name:/Show 1 player/i}).tap();
  await expect(players).toBeVisible();
  const controls=page.getByRole('complementary',{name:'Card actions',exact:true});
  const hand=page.getByRole('region',{name:'Your hand',exact:true});
  await expect(controls.getByRole('button',{name:'Draw card',exact:true})).toBeVisible();await expect(hand).toBeVisible();
  const boxes={players:await players.boundingBox(),controls:await controls.boundingBox(),hand:await hand.boundingBox()};
  expect(boxes.players.y+boxes.players.height).toBeLessThanOrEqual(boxes.controls.y);
  expect(boxes.controls.y+boxes.controls.height).toBeLessThanOrEqual(boxes.hand.y);
  expect(boxes.hand.y+boxes.hand.height).toBeLessThanOrEqual(845);
  observations.dock=boxes;
  await page.waitForTimeout(700);await page.screenshot({path:`${folder}/touch-dock-players-hand-open.png`,fullPage:true});
  await hand.getByRole('button',{name:'Inspect Queen of Clubs',exact:true}).tap();
  const dialog=page.getByRole('dialog',{name:'Inspecting Queen of Clubs',exact:true});await expect(dialog).toBeVisible();
  await expect(dialog.locator('.playing-card canvas')).toBeVisible();
  await page.screenshot({path:`${folder}/touch-queen-inspection.png`,fullPage:true});
  await page.getByRole('button',{name:'Close inspect',exact:true}).tap();await expect(dialog).toHaveCount(0);
  const card=hand.getByRole('button',{name:'Inspect Queen of Clubs',exact:true});const cardBox=await card.boundingBox();
  const cdp=await context.newCDPSession(page);
  watchActions=true;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:cardBox.x+cardBox.width/2,y:cardBox.y+cardBox.height/2,id:0,radiusX:5,radiusY:5,force:1}]});
  await page.waitForTimeout(650);
  const menu=page.getByRole('menu',{name:'Object actions',exact:true});const play=menu.getByRole('menuitem',{name:'Play to table',exact:true});
  await expect(play).toBeVisible();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});await page.waitForTimeout(250);
  await expect(menu).toBeVisible();await expect(card).toBeVisible();await expect(hand.locator('.hand-card')).toHaveCount(2);expect(actions).toEqual([]);
  observations.longPressRelease={menuRemainedOpen:true,handCount:2,actionRequestsBeforeExplicitTap:[...actions]};
  observations.menuHit=await play.evaluate(element=>{const box=element.getBoundingClientRect();const top=document.elementFromPoint(box.x+box.width/2,box.y+box.height/2);return top===element||element.contains(top);});
  expect(observations.menuHit).toBe(true);
  await page.screenshot({path:`${folder}/touch-hand-menu-hit.png`,fullPage:true});
  await play.tap();await expect(card).toHaveCount(0);await expect(menu).toHaveCount(0);await expect(hand.locator('.hand-card')).toHaveCount(1);
  await expect.poll(()=>actions).toEqual(['entity.grab','entity.drop']);observations.explicitMenuTapActions=actions;
  await page.screenshot({path:`${folder}/touch-menu-played-card.png`,fullPage:true});
  await page.getByRole('button',{name:'Close players',exact:true}).tap();await expect(players).toHaveCount(0);
  observations.overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  expect(observations.overflow).toBe(false);expect(errors).toEqual([]);
  observations.checks=['touch-open player tray with owned hand visible','stacked panels do not overlap','touch card inspection and close','native touch long press opens menu','release preserves menu and both hand cards without action requests','menu wins actual viewport hit test','fresh touch Play to table removes only the intended owned hand card','touch-close player tray'];
  await context.close();
}finally{await fs.writeFile(`${folder}/touch-observations.json`,JSON.stringify(observations,null,2));await browser.close();}
