import { test, expect } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";

const SOURCE = "8bed07f5bfed67b89cf52b5c6ce3baa7bdd97260";
const HASH = "e79d0701f988e78458443e8e2b43b98d334d981baf748b46611074c059ef880b";
test("the full pinned Merlin rulebook survives normal creation, unavailable-provider retry and request download", async ({ page }, info) => {
  const repository = process.env.MERLIN_ECONOMICS_SOURCE;
  if (!repository) throw new Error("Set MERLIN_ECONOMICS_SOURCE to the existing local SidewaysTurtle/MerlinEconomics checkout; this benchmark never substitutes another game.");
  const file = join(repository, "Merlin Economics Obsidian/Rulebook.md"), bytes = await readFile(file);
  expect(createHash("sha256").update(bytes).digest("hex")).toBe(HASH);
  const text = bytes.toString("utf8"), sourceUrl = `https://github.com/SidewaysTurtle/MerlinEconomics/blob/${SOURCE}/Merlin%20Economics%20Obsidian/Rulebook.md`;
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("Email address", { exact: true }).fill(`merlin-${Date.now()}@example.com`);
  await page.getByRole("button", { name: "Email me a link", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Check your email", exact: true })).toBeVisible();
  const { link } = await (await page.request.get("/api/dev/last-magic-link")).json();
  await page.goto(link); await page.goto("/create");
  const prompt = "Reproduce Merlin Economics v0.1.27b for 4–6 players. Use the complete attached rules; record unread linked Google Sheets and unresolved definitions. Create artwork for this game.";
  await page.getByLabel("Game description", { exact: true }).fill(prompt);
  const input = page.getByLabel("Attach rule or card files", { exact: true });
  await input.setInputFiles(file);
  const sources = page.getByRole("list", { name: "Attached source documents", exact: true });
  await expect(sources.locator("li")).toHaveCount(1);
  await expect(sources).toContainText("65,874 bytes");
  await sources.getByRole("textbox", { name: /Public source URL/ }).fill(sourceUrl);
  await sources.getByText("Source fingerprint", { exact: true }).click();
  await expect(sources.locator("code")).toHaveText(`sha256:${HASH}`);
  await page.screenshot({ path: info.outputPath("merlin-full-rules-desktop.png"), fullPage: true });
  await input.setInputFiles({ name: "Pixels.png", mimeType: "image/png", buffer: Buffer.from("binary") });
  await expect(page.locator(".rule-sources [role=alert]")).toContainText("text, Markdown or CSV");
  await expect(sources.locator("li")).toHaveCount(1);
  await input.setInputFiles({ name: "Too-large.md", mimeType: "text/markdown", buffer: Buffer.alloc(131_073, 120) });
  await expect(page.locator(".rule-sources [role=alert]")).toContainText("128 KiB");
  await expect(sources.locator("code")).toHaveText(`sha256:${HASH}`);
  await page.setViewportSize({ width: 390, height: 480 });
  const urlField = sources.getByRole("textbox", { name: /Public source URL/ });
  await urlField.focus(); await urlField.scrollIntoViewIfNeeded();
  const box = await urlField.boundingBox();
  expect(box?.y).toBeGreaterThanOrEqual(0); expect(box!.y + box!.height).toBeLessThanOrEqual(480);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: info.outputPath("merlin-source-short.png"), fullPage: false });
  await page.setViewportSize({ width: 390, height: 844 });
  const submitted = page.waitForResponse((response) => response.url().endsWith("/api/ai/games") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Create & play", exact: true }).click();
  const response = await submitted;
  expect(response.status()).toBe(503);
  expect(await response.json()).toMatchObject({ error: { code: "ai_unconfigured" } });
  const request = response.request().postDataJSON();
  expect(request).toEqual({ prompt, references: [{ name: "Rulebook.md", text, sourceUrl }] });
  await expect(page.locator(".ai-state-unconfigured")).toContainText("isn't set up");
  await expect(page.getByLabel("Game description", { exact: true })).toHaveValue(prompt);
  const retry = page.getByRole("button", { name: "Retry AI draft", exact: true });
  await expect(retry).toBeEnabled(); await retry.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("merlin-unconfigured-recovery-390.png"), fullPage: false });
  const again = page.waitForResponse((r) => r.url().endsWith("/api/ai/games") && r.request().method() === "POST");
  await retry.click(); const retryResponse = await again;
  expect(retryResponse.status()).toBe(503); expect(retryResponse.request().postDataJSON()).toEqual(request);
  await retry.focus(); await page.keyboard.press("Tab");
  await expect(page.getByRole("button", { name: "Download generation request", exact: true })).toBeFocused();
  const downloading = page.waitForEvent("download"); await page.keyboard.press("Enter");
  const requestPath = info.outputPath("merlin-full-source.request.json"); await (await downloading).saveAs(requestPath);
  expect(JSON.parse(await readFile(requestPath, "utf8"))).toEqual(request);
  await expect(page).toHaveURL(/\/create$/);
  expect((await (await page.request.get("/api/games/mine")).json()).games).toHaveLength(0);
  expect(errors).toEqual([]);
  const catalogs = [...text.matchAll(/\[([^\]]+)\]\((https:\/\/docs\.google\.com\/spreadsheets\/d\/[^)]+)\)/g)].map((match) => ({ name: match[1], sourceUrl: match[2], read: false }));
  expect(catalogs).toHaveLength(7);
  await writeFile(info.outputPath("merlin-attempt-receipt.json"), JSON.stringify({ sourceCommit: SOURCE, sourceSha256: HASH, sourceBytes: bytes.length,
    normalFormAndApiUsed: true, exactSourceTextRetained: true, response: { status: 503, code: "ai_unconfigured" }, retryPreservedRequest: true,
    requestDownloadExact: true, externalCatalogs: catalogs, fixtureModelUsed: false, liveGenerationVerified: false, fullMerlinGameAccepted: false,
    scope: "Real pinned source intake/recovery with an intentionally unconfigured isolated server; no model output or game/fun/art-quality acceptance." }, null, 2));
});
